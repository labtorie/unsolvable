const PREFIX = ['', '', '', '', 'Главные ', 'Объединённые ', 'Народные ', 'Первые ', 'Вторые ', 'Новые ', 'Великие '];

const ROMAN = ['', ' II', ' III', ' IV', ' V', ' VI', ' VII', ' VIII', ' IX', ' X'];

/** Название для новой фирмы; avoid — множество уже занятых имён. */
export function firmName(world, industry, avoid, kind = 'private') {
  const stems = STEMS[industry] || STEMS.services;
  for (let attempt = 0; attempt < 40; attempt++) {
    const stem = stems[Math.floor(rand(world) * stems.length)];
    const suf = SUFFIX[Math.floor(rand(world) * SUFFIX.length)];
    let pre = PREFIX[Math.floor(rand(world) * PREFIX.length)];
    if (kind === 'state') pre = 'Госпредприятие ';
    else if (kind === 'coop') pre = 'Артель ';
    const name = pre + stem + suf;
    if (!avoid || !avoid.has(name)) return name;
  }
  const stem = stems[Math.floor(rand(world) * stems.length)];
  for (let i = 1; i < ROMAN.length; i++) {
    const n = stem + ROMAN[i];
    if (!avoid || !avoid.has(n)) return n;
  }
  return stem + ' #' + Math.floor(rand(world) * 1e6);
}

/** Имя дочерней фирмы при разделе. */
export function splitName(base, avoid) {
  base = base.replace(/ (II|III|IV|V|VI|VII|VIII|IX|X)$/, '');
  for (let i = 2; i < 30; i++) {
    const n = base + ' ' + (i <= 10 ? ROMAN[i - 1].trim() : i);
    if (!avoid || !avoid.has(n)) return n;
  }
  return base + ' (осколок)';
}

